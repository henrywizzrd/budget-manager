// Generates src/components/icons/iconData.ts from design/icons/icons.json (run: node scripts/gen-icons.mjs)
import fs from 'node:fs';
const d = JSON.parse(fs.readFileSync('design/icons/icons.json', 'utf8'));
const attr = (s, k) => { const m = s.match(new RegExp(`\\s${k}="([^"]*)"`)); return m ? m[1] : undefined; };
function parse(svg) {
  const out = []; const stack = [out];
  const re = /<(\/?)(g|path|circle|rect|ellipse)\b([^>]*?)(\/?)>/g; let m;
  while ((m = re.exec(svg))) {
    const [, close, tag, rest, self] = m;
    if (close) { stack.pop(); continue; }
    const el = { t: tag };
    for (const k of ['class', 'd', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'transform', 'fill']) {
      const v = attr(' ' + rest, k); if (v !== undefined) el[k === 'class' ? 'c' : k] = v;
    }
    stack[stack.length - 1].push(el);
    if (tag === 'g' && !self) { el.k = []; stack.push(el.k); }
  }
  return out;
}
const icons = Object.fromEntries(d.icons.map((i) => [i.id, { g: i.g, vi: i.vi, en: i.en, el: parse(i.svg) }]));
const groups = Object.fromEntries(d.groups.map((g) => [g.id, { vi: g.vi, en: g.en, c: g.c }]));
fs.writeFileSync('src/components/icons/iconData.ts',
  `// Generated by scripts/gen-icons.mjs from design/icons/icons.json. Do not edit by hand.\n// 60 glyphs from Phosphor Icons (MIT, design/icons/LICENSE-phosphor); 5 drawn for MYX.\n` +
  `export type IconEl = { t: string; c?: string; d?: string; cx?: string; cy?: string; r?: string; rx?: string; ry?: string; x?: string; y?: string; width?: string; height?: string; transform?: string; fill?: string; k?: IconEl[] };\n` +
  `export const ICON_GROUPS: Record<string, { vi: string; en: string; c: string }> = ${JSON.stringify(groups)};\n` +
  `export const ICONS: Record<string, { g: string; vi: string; en: string; el: IconEl[] }> = ${JSON.stringify(icons)};\n`);
console.log('icons:', Object.keys(icons).length);
